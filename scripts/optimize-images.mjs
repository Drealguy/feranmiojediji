// Shrinks project screenshots and generates blur placeholders.
// Run after adding new screenshots:  node scripts/optimize-images.mjs
//
// - Resizes every JPG/PNG in public/projects/** to at most MAX_WIDTH wide and re-encodes it
//   (JPG with mozjpeg), only replacing the file when the result is smaller.
// - Writes lib/image-blur.ts: a tiny blurred preview (base64) for each image, shown while it loads.
import sharp from "sharp";
import { readdirSync, statSync, writeFileSync, renameSync } from "node:fs";
import { join, relative, extname } from "node:path";

const ROOT = "public/projects";
const MAX_WIDTH = 1600;
const QUALITY = 78;

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(ROOT).filter((f) => /\.(jpe?g|png)$/i.test(f));
const blur = {};
let saved = 0;

for (const file of files) {
  const before = statSync(file).size;
  const img = sharp(file);
  const { width } = await img.metadata();
  const isJpg = /\.jpe?g$/i.test(extname(file));

  let pipeline = sharp(file).rotate();
  if (width > MAX_WIDTH) pipeline = pipeline.resize({ width: MAX_WIDTH });
  pipeline = isJpg ? pipeline.jpeg({ quality: QUALITY, mozjpeg: true }) : pipeline.png({ compressionLevel: 9, palette: true });
  const tmp = `${file}.tmp`;
  await pipeline.toFile(tmp);
  const after = statSync(tmp).size;
  if (after < before) {
    renameSync(tmp, file);
    saved += before - after;
  } else {
    // Keep the original; it was already small enough.
    renameSync(tmp, `${file}.unused`);
    (await import("node:fs")).unlinkSync(`${file}.unused`);
  }

  const tiny = await sharp(file).resize(16).blur().webp({ quality: 40 }).toBuffer();
  blur["/" + relative("public", file).replace(/\\/g, "/")] = `data:image/webp;base64,${tiny.toString("base64")}`;
  console.log(`${file}: ${(before / 1024).toFixed(0)} KB -> ${(Math.min(before, after) / 1024).toFixed(0)} KB`);
}

writeFileSync(
  "lib/image-blur.ts",
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.
/** Tiny blurred previews for project images, keyed by their /public path. */
export const imageBlur: Record<string, string> = ${JSON.stringify(blur, null, 2)};
`,
);
console.log(`\n${files.length} images, saved ${(saved / 1024 / 1024).toFixed(1)} MB`);
